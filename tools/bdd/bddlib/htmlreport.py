def esc(value: object) -> str:
    return html.escape(str(value), quote=True)


def badge(text: object, kind: str) -> str:
    return f'<span class="badge {kind}">{esc(text)}</span>'


def result_badge(result: str | None) -> str:
    return badge(result, RESULT_KIND.get(result, WARN)) if result else '<span class="muted">-</span>'


def table(headers: list[str], rows: list[list[str]]) -> str:
    """A table whose cells are already HTML."""
    head = "".join(f"<th>{esc(h)}</th>" for h in headers)
    body = "".join("<tr>" + "".join(f"<td>{cell}</td>" for cell in row) + "</tr>" for row in rows)
    return f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"


def count(number: int, noun: str) -> str:
    return f"{number} {noun}" + ("" if number == 1 else "s")


def card(label: str, value: str) -> str:
    return f'<div class="card"><b>{esc(label)}</b>{value}</div>'


def section(anchor: str, title: str, body: list[str]) -> list[str]:
    return [f'<h2 id="{anchor}">{esc(title)}</h2>', *body]


# -- what each scenario did, from the recorded runs ----------------------------------------------
def scenario_results(root: Path, feature_id: str, data: dict) -> dict[str, dict[str, str]]:
    """example id -> {"red": result, "latest": result}, from the red run kept at the bind gate and the latest run."""
    rules = list(cfg.load(root).runs)
    if not rules:
        return {}
    try:
        scenarios = classify.feature_scenarios(root, feature_id)
    except (UsageError, FileNotFoundError):
        return {}
    loaders = {"red": lambda: runner.load_red(root, feature_id, data.get("red_run")), "latest": lambda: runner.load_latest(root, feature_id)}
    found: dict[str, dict[str, str]] = {}
    for label, load in loaders.items():
        try:
            report = classify.classify_run(load(), scenarios, rules)
        except (UsageError, StoreError, OSError):
            continue
        for row in report["scenarios"]:
            if row["example"]:
                found.setdefault(row["example"], {})[label] = row["result"]
    return found


# -- the sections ------------------------------------------------------------------------------
def verdict_kind(valid: bool | None) -> str:
    return WARN if valid is None else GOOD if valid else BAD


def run_card(label: str, run: dict | None) -> str:
    if run is None:
        return card(label, badge("no recorded run", WARN))
    verdict = "valid" if run["valid"] else "not valid" if run["valid"] is False else "recorded"
    outcomes = ", ".join(f"{n} {k}" for k, n in sorted(run["outcomes"].items())) or "no cases"
    return card(label, badge(verdict, verdict_kind(run["valid"])) + f'<div class="muted">{esc(outcomes)}</div>')


def header(facts: dict) -> list[str]:
    runs, audit, level = facts["runs"], facts["audit"], facts["enforcement"]["level"]
    kind = " (adoption: describes behaviour that already existed)" if facts["kind"] == "adopt" else ""
    out = [f"<h1>{esc(facts['feature'])}: {esc(facts['title'])}</h1>", f'<p class="muted">Phase <b>{esc(facts["phase"])}</b>{esc(kind)}</p>']
    if facts["unreviewed"]:
        out.append('<div class="banner"><b>UNREVIEWED.</b> This feature ran under autopilot: no person answered the questions or '
                   "approved the rules and examples. Read the assumptions below before relying on it.</div>")
    if level == "soft":
        reasons = "".join(f"<li>{esc(reason)}</li>" for reason in facts["enforcement"]["reasons"])
        out.append(f'<div class="banner"><b>Soft enforcement.</b> Violations were detected after the fact, not prevented.<ul>{reasons}</ul></div>')
    verdict = (audit or {}).get("verdict")
    out.append('<div class="cards">' + "".join([
        card("Enforcement", badge(level, GOOD if level == "hard" else WARN)),
        card("Autonomy", esc(facts["autonomy"]["level"])),
        card("Audit verdict", badge(verdict or "no report yet", GOOD if verdict == "PASS" else WARN if verdict is None else BAD)),
        run_card("Red run", runs["red"]), run_card("Latest run", runs["latest"]),
        card("Traceability", badge("no gaps", GOOD) if not facts["trace"]["gaps"] else badge(f"{len(facts['trace']['gaps'])} gap(s)", BAD)),
    ]) + "</div>")
    out.append('<nav><a href="#summary">Summary</a><a href="#rules">Rules and examples</a><a href="#evidence">Evidence</a>'
               '<a href="#checks">Checks</a><a href="#audit">Audit</a><a href="#cost">Cost</a></nav>')
    return out


def summary(facts: dict) -> list[str]:
    text = esc(facts["summary"]) if facts["summary"] else '<span class="muted">The brief has no summary.</span>'
    body = [f"<p>{text}</p>"]
    if facts["assumptions"]:
        rows = [[esc(a["id"]), esc(a["text"]), esc(a["rationale"])] for a in facts["assumptions"]]
        body += ["<h3>Assumptions</h3>", table(["Id", "Assumption", "Because"], rows)]
    return section("summary", "Summary", body)


def rules_section(facts: dict, results: dict[str, dict[str, str]]) -> list[str]:
    totals = facts["trace"]["totals"]
    title = f"Rules and examples ({count(totals['rules'], 'rule')}, {count(totals['examples'], 'example')}, {count(totals['scenarios'], 'scenario')})"
    body: list[str] = []
    for rule in facts["trace"]["rules"]:
        body.append(f"<h3><code>{esc(rule['id'])}</code> {esc(rule['text'])}</h3>")
        rows = []
        for example in rule["examples"]:
            names = "<br>".join(esc(s["name"]) for s in example["scenarios"]) or badge("no scenario", BAD)
            seen = results.get(example["id"], {})
            tasks = esc(", ".join(example["tasks"])) or '<span class="muted">-</span>'
            rows.append([f"<code>{esc(example['id'])}</code> {esc(example['text'])}", names,
                         result_badge(seen.get("red")), result_badge(seen.get("latest")), tasks])
        body.append(table(["Example", "Scenario", "Red run", "Latest run", "Tasks"], rows) if rows else '<p class="muted">No example yet.</p>')
    if facts["trace"]["gaps"]:
        body += ["<h3>Traceability gaps</h3>", "<ul>" + "".join(f"<li><code>{esc(g['code'])}</code> {esc(g['message'])}</li>" for g in facts["trace"]["gaps"]) + "</ul>"]
    return section("rules", title, body)


def approval_row(approval: dict) -> list[str]:
    word = pr.DECISION_WORD.get(approval["decision"], approval["decision"])
    valid = approval["decision"] != "approve" or approval["valid"]
    return [esc(approval["gate"]), badge(word, GOOD if approval["decision"] == "approve" and valid else BAD), esc(approval["origin"]),
            badge("valid", GOOD) if valid and approval["decision"] == "approve" else badge("not valid now", BAD) if not valid else "",
            esc(approval["reason"])]


def evidence(facts: dict) -> list[str]:
    gates = [[esc(name), badge(g["result"], GOOD if g["result"] == "pass" else BAD)] for name, g in facts["gates"].items()]
    locks = facts["locks"]
    lock_text = badge("none", WARN) if not locks["scopes"] else badge("intact", GOOD) if locks["intact"] else badge("NOT intact", BAD)
    body = ["<h3>Gates</h3>", table(["Gate", "Result"], gates) if gates else '<p class="muted">No gate has passed yet.</p>',
            "<h3>Approvals</h3>",
            table(["Gate", "Decision", "How", "Now", "Reason"], [approval_row(a) for a in facts["approvals"]]) if facts["approvals"]
            else '<p class="muted">No approval recorded.</p>',
            f"<h3>Locks</h3><p>{lock_text} {esc(', '.join(locks['scopes']))}</p>"]
    if locks["problems"]:
        body.append("<ul>" + "".join(f"<li>{esc(p)}</li>" for p in locks["problems"]) + "</ul>")
    if facts["changes"]:
        body.append(f"<p>Approved work was changed {esc(facts['changes'])} time(s) through the change flow.</p>")
    return section("evidence", "Evidence", body)


def checks_section(facts: dict) -> list[str]:
    checks, rows = facts["checks"], []
    if checks["quality"]:
        names = ", ".join(f"{c['name']} {'ok' if c['passed'] else 'FAILED'}" for c in checks["quality"]["checks"])
        rows.append(["Quality checks", badge("passed" if checks["quality"]["passed"] else "FAILED", GOOD if checks["quality"]["passed"] else BAD), esc(names)])
    mutated = checks["mutation"]
    if mutated:
        score = "no score" if mutated["score"] is None else f"{mutated['score']:g}% killed"
        rows.append(["Mutation check", badge("passed" if mutated["passed"] else "FAILED", GOOD if mutated["passed"] else BAD),
                     esc(f"{score}, threshold {mutated['threshold']:g}%, {mutated['files']} file(s) {mutated['note']}".strip())])
    stable = checks["stability"]
    if stable:
        flaky = "?" if stable["flaky"] is None else stable["flaky"]
        rows.append(["Stability", badge("passed" if stable["passed"] else "FAILED", GOOD if stable["passed"] else BAD), esc(f"{stable['runs']} run(s), {flaky} flaky scenario(s)")])
    body = [table(["Check", "Result", "Detail"], [[esc(r[0]), r[1], r[2]] for r in rows])] if rows else ['<p class="muted">No quality, mutation or stability check was run.</p>']
    return section("checks", "Checks", body)


def audit_section(facts: dict) -> list[str]:
    audit = facts["audit"]
    if audit is None:
        return section("audit", "Audit", ['<p class="muted">No audit report yet: the verify phase has not run.</p>'])
    body = [f"<p>Verdict {badge(audit['verdict'] or 'unknown', GOOD if audit['verdict'] == 'PASS' else BAD)} "
            f"<span class=\"muted\">review status: {esc(audit['review'] or 'unknown')}</span></p>"]
    for title, key in pr.FINDING_GROUPS:
        items = [i for i in audit[key] if i.strip().strip("<>") not in ("", "none")]
        body.append(f"<h3>{esc(title)}</h3>" + ("<ul>" + "".join(f"<li>{esc(i)}</li>" for i in items) + "</ul>" if items else '<p class="muted">none</p>'))
    return section("audit", "Audit", body)


def cost_section(facts: dict) -> list[str]:
    if not facts["cost"]:
        return section("cost", "Cost", ['<p class="muted">No cost recorded.</p>'])
    rows = [[esc(phase), esc(c["tokens"]), esc(f"{c['seconds']:g}")] for phase, c in facts["cost"].items()]
    return section("cost", "Cost", [table(["Phase", "Tokens", "Seconds"], rows)])


def render(facts: dict, results: dict[str, dict[str, str]]) -> str:
    body = [*header(facts), *summary(facts), *rules_section(facts, results), *evidence(facts), *checks_section(facts), *audit_section(facts),
            *cost_section(facts), f"<footer>Built by <code>bdd report</code> from the records of {esc(facts['feature'])} at {esc(store.utc_now())}. "
            "It states what the records state, nothing more.</footer>"]
    return (f'<!DOCTYPE html>\n{MARKER}\n<html lang="en"><head><meta charset="utf-8">'
            '<meta name="viewport" content="width=device-width, initial-scale=1">'
            f"<title>{esc(facts['feature'])}: {esc(facts['title'])}</title><style>{STYLE}</style></head>"
            f"<body><main>{''.join(body)}</main></body></html>\n")


# -- writing the page ----------------------------------------------------------------------------
def refusal(root: Path, target: Path) -> str | None:
    """Why the page may not be written to [target], or None when it may."""
    key, data = path_key(target), path_key(root / cfg.BDD_DIR)       # the same key for every spelling: case, `..`, links
    if key == data or key.startswith(data + "/"):
        return f"{cfg.BDD_DIR}/ holds the records; write the report elsewhere"
    here = Path(os.path.abspath(root))
    inside = Path(os.path.abspath(target))
    below = [inside, *(parent for parent in inside.parents if here in parent.parents)] if here in inside.parents else [inside, inside.parent]
    for part in below:                                  # the file and the folders the page would be written through
        if part.is_symlink():
            return f"{part} is a link; a report is never written through a link"
    if inside.is_dir():
        return f"{target} is a folder"
    if inside.exists() and MARKER not in inside.read_text(encoding="utf-8", errors="replace")[:MARKER_WINDOW]:
        return f"{target} exists and was not written by bdd report; it is never replaced"
    return None


def write(root: Path, target: Path, text: str) -> None:
    problem = refusal(root, target)
    if problem:
        raise UsageError(problem)
    target.parent.mkdir(parents=True, exist_ok=True)
    handle, name = tempfile.mkstemp(dir=target.parent, prefix=".report-", suffix=".tmp")      # a new file nobody else can have made
    try:
        with os.fdopen(handle, "w", encoding="utf-8", newline="\n") as page:
            page.write(text)
        os.chmod(name, 0o644)                           # a report is meant to be shared
        os.replace(name, target)
    except OSError:
        Path(name).unlink(missing_ok=True)
        raise


def run(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(prog="bdd report", description="A readable HTML report of a feature, from its records.")
    ap.add_argument("feature", help="feature id, e.g. FEAT-007")
    ap.add_argument("--out", type=Path, help="write the page to this path instead of stdout")
    args = ap.parse_args(argv)

    def action() -> int:
        root = project_root()
        feature_dir = store.find_feature_dir(root, args.feature)
        facts = pr.collect(root, feature_dir)
        page = render(facts, scenario_results(root, facts["feature"], state.load(feature_dir)))
        if args.out is None:
            sys.stdout.write(page)
            return 0
        write(root, args.out, page)
        print(f"{args.feature}: wrote {args.out}")
        return 0

    try:
        return guarded("report", action)
    except cfg.ConfigError as exc:
        print(f"bdd report: {exc}", file=sys.stderr)
        return 2
